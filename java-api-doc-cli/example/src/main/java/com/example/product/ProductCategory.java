package com.example.product;

/**
 * 商品类别的枚举定义。
 *
 * <p>用于划分商品所属的分类，如电子产品、服装、食品、书籍等。</p>
 *
 * @author example
 * @see Product
 * @see ProductService
 */
public enum ProductCategory {

    /** 电子产品（手机、电脑、配件等） */
    ELECTRONICS,

    /** 服装（上衣、裤子、鞋帽等） */
    CLOTHING,

    /** 食品（零食、饮料、生鲜等） */
    FOOD,

    /** 书籍（纸质书、电子书等） */
    BOOKS
}
